#!/usr/bin/env python3
"""render_surface_env — project the declared editable surface into an env file.

The TS reflex-engine and the shell-sourced meditation runner cannot import `harness_config`, so
this renders `harness/editable_surface.json` to `harness/surface.env` as OS_HARNESS_<KEY>=<value>
lines. One declaration, two runtimes -- the alternative (copying the numbers into meditation.env
and the TS constants) is the copy-pasted-constant anti-pattern that drifts silently.

Generated file. Never hand-edit surface.env; edit the JSON and re-render. Idempotent: safe to run
at engine start and from a validation worktree.

Usage:  python3 bin/render_surface_env.py [--check]
        --check exits 1 if the rendered file is stale (for CI/doctor), writing nothing.
"""
from __future__ import annotations

import sys
from pathlib import Path

_GOV_ROOT = Path(__file__).resolve().parents[2]
if str(_GOV_ROOT) not in sys.path:
    sys.path.insert(0, str(_GOV_ROOT))

from agentica_core import harness_config  # noqa: E402

_OUT = Path(__file__).resolve().parents[1] / "harness" / "surface.env"

_HEADER = (
    "# GENERATED by bin/render_surface_env.py from harness/editable_surface.json.\n"
    "# Do not hand-edit: edit the JSON declaration and re-render.\n"
)


def render() -> str:
    """Header + fingerprint + one OS_HARNESS_<KEY>=<value> line per declared knob.

    The fingerprint is emitted here rather than recomputed by each consumer: hashing the same
    JSON in two languages is the copy-pasted-constant anti-pattern, and a TS/Python canonicalisation
    that drifted by one space would silently label every trace with the wrong harness version.
    """
    lines = harness_config.as_env_lines()
    return (
        _HEADER
        + f"OS_HARNESS_FINGERPRINT={harness_config.surface_fingerprint()}\n"
        + "\n".join(lines)
        + "\n"
    )


def main(argv: list[str]) -> int:
    body = render()
    if "--check" in argv:
        current = _OUT.read_text(encoding="utf-8") if _OUT.exists() else ""
        if current != body:
            print(f"STALE: {_OUT} does not match editable_surface.json — re-run without --check")
            return 1
        print(f"OK: {_OUT} is current")
        return 0

    _OUT.parent.mkdir(parents=True, exist_ok=True)
    tmp = Path(str(_OUT) + ".tmp")
    try:
        tmp.write_text(body, encoding="utf-8")
        tmp.replace(_OUT)  # atomic: a sourcing shell must never read a half-written env file
    except Exception:
        if tmp.exists():
            try:
                tmp.unlink()
            except OSError:
                pass
        raise
    print(f"wrote {_OUT} ({len(harness_config.as_env_lines())} keys, fingerprint "
          f"{harness_config.surface_fingerprint()})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
