"""`samurai audit`: one full audit of this machine, written where the dashboard reads it.

Reuses what already exists instead of a second implementation of any check:
  * `samurai doctor` -- hook registration, packaged-hook execution, posture, paths
  * bin/first_blood.py -- estimated agent spend from Claude Code session logs
  * weekly_report.generate -- per-week telemetry reports, when telemetry exists

Writes audit__<UTC stamp>.md into the reports directory and rebuilds its index.json,
which the dashboard's Reports tab lists. Read-only toward everything else.

This module is standard library only. first_blood and weekly_report need the report
dependencies, which bin/install.sh may have put in ~/.samurai/venv (PEP 668 Pythons),
so they run as subprocesses under that interpreter.
"""
from __future__ import annotations

import json
import os
import re
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

from .report_index import rebuild_index

DOCTOR_TIMEOUT_S = 180
FIRST_BLOOD_TIMEOUT_S = 300
WEEKLY_TIMEOUT_S = 300
_CHECK = re.compile(r"^\[(?:✅ )?(PASS|FAIL)\] ([^:]+): ?(.*)$")
_SUMMARY = re.compile(r"Summary: (\d+)/(\d+) checks passed")


def _cell(value) -> str:
    """Table-safe text. The dashboard's renderer passes inline <svg> through verbatim, so
    angle brackets from session-log directory names never reach it."""
    return str(value).replace("|", "\\|").replace("\n", " ").replace("<", "‹").replace(">", "›")


def report_python(samurai_home: Path) -> str:
    """The interpreter bin/install.sh installed the report dependencies for."""
    venv = Path(samurai_home) / "venv" / "bin" / "python"
    return str(venv) if os.access(venv, os.X_OK) else sys.executable


def _run(argv: list[str], timeout: int, env: dict | None = None,
         cwd: Path | None = None) -> tuple[int | None, str, str]:
    """(exit code or None if it never finished, stdout, last stderr line)."""
    try:
        done = subprocess.run(argv, stdin=subprocess.DEVNULL, capture_output=True,
                              text=True, timeout=timeout, env=env, cwd=cwd)
    except (OSError, subprocess.TimeoutExpired) as exc:
        return None, f"could not run: {type(exc).__name__}", type(exc).__name__
    lines = done.stderr.strip().splitlines()
    return done.returncode, done.stdout, lines[-1] if lines else ""


def run_doctor(root: Path) -> dict:
    code, out, _ = _run([sys.executable, str(root / "bin" / "samurai"), "doctor"], DOCTOR_TIMEOUT_S)
    checks = []
    for line in out.splitlines():
        m = _CHECK.match(line.replace("❌ ", "").strip())
        if m:
            checks.append({"result": m.group(1), "name": m.group(2).strip(), "detail": m.group(3).strip()})
    summary = _SUMMARY.search(out)
    passed, total = (int(summary.group(1)), int(summary.group(2))) if summary else (0, len(checks))
    return {"ok": code == 0, "ran": code is not None, "checks": checks,
            "passed": passed, "total": total, "error": None if code is not None else out}


def _core_env(root: Path, **extra: str) -> dict:
    path = os.environ.get("PYTHONPATH")
    return {**os.environ, "PYTHONPATH": f"{root}{os.pathsep}{path}" if path else str(root), **extra}


def run_first_blood(root: Path, logs_dir: Path, python: str) -> tuple[dict | None, str]:
    """(report, error): the report, or None and why the scan could not run."""
    code, out, err = _run([python, str(root / "bin" / "first_blood.py"), "--json",
                           "--logs-dir", str(logs_dir)], FIRST_BLOOD_TIMEOUT_S, env=_core_env(root))
    if code != 0:
        return None, err or f"exit {code}"
    try:
        return json.loads(out), ""
    except ValueError:
        return None, "unreadable output"


def run_weekly(root: Path, directory: Path, python: str) -> int | None:
    """Weekly reports written from local telemetry; None when generation failed.
    A broken telemetry store must not sink the audit."""
    code, _, _ = _run([python, "-m", "agentica_core.weekly_report"], WEEKLY_TIMEOUT_S,
                   env=_core_env(root, SAMURAI_REPORTS_DIR=str(directory)), cwd=root)
    if code != 0:
        return None
    return sum(1 for e in rebuild_index(directory) if e.get("kind") == "weekly")


def _money(v) -> str:
    return "—" if v is None else f"${v:,.2f}"


def render(now: datetime, version: str, doctor: dict, spend: dict | None, logs_dir: Path,
           weekly: int | None, spend_error: str = "", root: Path | None = None) -> str:
    lines = [f"# Full Audit — {now:%Y-%m-%d %H:%M} UTC", "",
             f"_Generated by `samurai audit` (Order Samurai v{version}). Analysis ran locally; "
             f"nothing left this machine._", ""]

    sessions = spend["sessions_scanned"] if spend else None
    health = (f"{doctor['passed']}/{doctor['total']} passed" if doctor["ran"]
              else "doctor could not run")
    lines += ["## Summary", "", "| Area | Result |", "| --- | --- |",
              f"| Health checks | {_cell(health)} |",
              f"| Sessions scanned | {'—' if sessions is None else sessions} |",
              f"| Estimated spend | {_money(spend.get('total_cost')) if spend else '—'} |",
              f"| Spend spikes | {len(spend['spend_spikes']) if spend else '—'} |",
              f"| Weekly telemetry reports | {'failed' if weekly is None else weekly} |", ""]

    lines += ["## Health checks", ""]
    if not doctor["ran"]:
        lines += [f"`samurai doctor` {_cell(doctor['error'])}.", ""]
    else:
        lines += ["| Check | Result | Detail |", "| --- | --- | --- |"]
        lines += [f"| {_cell(c['name'])} | {c['result']} | {_cell(c['detail'])} |" for c in doctor["checks"]]
        lines += ["", "**All checks passed.**" if doctor["ok"] else
                  "**Some checks failed.** Run `samurai doctor` for the fix each one names.", ""]

    lines += ["## Agent spend", ""]
    if spend is None:
        lines += [f"The session-log scan could not run: `{_cell(spend_error or 'unknown error')}`.", ""]
        if "ModuleNotFoundError" in spend_error and root is not None:
            lines += [f"Install the report dependencies with `bash {_cell(root)}/bin/install.sh`, "
                      "then run `samurai audit` again.", ""]
    elif not spend["sessions_scanned"]:
        lines += [f"No Claude Code session logs found under `{_cell(logs_dir)}`. Run a Claude Code "
                  "session, then `samurai audit` again.", ""]
    else:
        lines += [f"Sessions scanned: **{spend['sessions_scanned']}**", "",
                  "| Metric | Value |", "| --- | --- |",
                  f"| Total cost (estimated) | {_money(spend.get('total_cost'))} |",
                  f"| Cost per session (estimated) | {_money(spend.get('cost_per_task'))} |",
                  f"| Token spend | {spend.get('token_spend') or 0:,} |",
                  f"| Token execution density | {spend.get('token_execution_density') or '—'} |", ""]
        spikes = spend.get("spend_spikes") or []
        threshold = spend.get("spend_spike_threshold_usd")
        if spikes:
            lines += [f"Sessions at or above ${threshold:g} (spend spikes):", "",
                      "| Project | Session | Estimated cost |", "| --- | --- | --- |"]
            lines += [f"| {_cell(s.get('project'))} | {_cell((s.get('session_id') or '')[:8])} | "
                      f"{_money(s.get('estimated_cost'))} |" for s in spikes]
            lines.append("")
        else:
            lines += [f"No session reached the ${threshold:g} spend-spike threshold.", ""]
        lines += [f"_{_cell(spend.get('note', ''))}_", ""]

    lines += ["## Weekly telemetry", ""]
    if weekly is None:
        lines += ["Weekly report generation failed; the rest of this audit is unaffected.", ""]
    elif weekly:
        lines += [f"{weekly} weekly report(s) are listed beside this audit in the Reports tab.", ""]
    else:
        lines += ["No local telemetry yet. Weekly reports appear here as agent sessions are recorded.", ""]
    return "\n".join(lines)


def run_audit(root: Path, directory: Path, logs_dir: Path, version: str,
              samurai_home: Path, now: datetime | None = None) -> dict:
    """Run every part, write the report and index. Raises OSError if it cannot write."""
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    doctor = run_doctor(root)
    python = report_python(samurai_home)
    spend, spend_error = run_first_blood(root, logs_dir, python)
    weekly = run_weekly(root, directory, python)
    # Stamped after the weekly rewrite, so the new audit sorts first in the index.
    now = now or datetime.now(timezone.utc)
    path = directory / f"audit__{now:%Y%m%dT%H%M%SZ}.md"
    path.write_text(render(now, version, doctor, spend, logs_dir, weekly, spend_error, root),
                    encoding="utf-8")
    rebuild_index(directory)
    return {"path": path, "doctor": doctor, "spend": spend, "weekly": weekly}
